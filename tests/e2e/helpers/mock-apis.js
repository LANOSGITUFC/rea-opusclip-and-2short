/**
 * Local HTTP mock server for external APIs:
 * Groq, OpenAI, OpenRouter, Gemini, Giphy, Google OAuth, YouTube, TikTok, Instagram/Meta.
 * Supports configurable failure injection and request logging for E2E assertions.
 */
"use strict";

const http = require("node:http");

function extractApiKey(req, urlObj) {
  const auth = req.headers["authorization"] || "";
  if (auth.toLowerCase().startsWith("bearer ")) {
    return auth.slice(7).trim();
  }
  const queryKey = urlObj.searchParams.get("key") || urlObj.searchParams.get("api_key");
  return queryKey ? queryKey.trim() : "";
}

function buildDefaultChatContent(bodyText, targetHost) {
  let lower = (bodyText || "").toLowerCase();
  if (lower.includes("viral") || lower.includes("clips") || lower.includes("curate") || lower.includes("hook")) {
    return JSON.stringify({
      clips: [
        {
          title: "Mock Viral Hook Clip",
          description: "High retention mock clip generated by test server",
          hashtags: "#shorts #viral #mock",
          viralityScore: 92,
          hookScore: 94,
          pacingScore: 89,
          storyScore: 90,
          reason: "Strong opening hook and concise pacing",
          startSec: 0,
          endSec: 5.5
        }
      ]
    });
  }
  if (lower.includes("translat") || lower.includes("traduz") || lower.includes("idioma")) {
    return JSON.stringify({
      language: "en",
      translatedText: "Hello world translated clip",
      segments: [{ id: 0, start: 0.1, end: 2.5, text: "Hello world translated clip" }],
      words: [
        { text: "Hello", start: 0.1, end: 0.5 },
        { text: "world", start: 0.6, end: 1.0 },
        { text: "translated", start: 1.1, end: 1.8 },
        { text: "clip", start: 1.9, end: 2.5 }
      ]
    });
  }
  if (lower.includes("emoji")) {
    return JSON.stringify({
      emojis: [
        { wordIndex: 0, word: "Hello", emoji: "👋" },
        { wordIndex: 1, word: "world", emoji: "🌍" }
      ]
    });
  }
  if (lower.includes("social") || lower.includes("legenda") || lower.includes("hashtag")) {
    return JSON.stringify({
      title: "Mock Social Short Title",
      description: "Engaging mock social media description for testing.",
      hashtags: "#shorts #reels #tiktok #viral"
    });
  }
  if (lower.includes("b-roll") || lower.includes("broll") || lower.includes("giphy")) {
    return JSON.stringify({
      queries: ["technology", "coding"],
      suggestions: [{ timeSec: 0.5, query: "technology" }]
    });
  }
  return `Mock LLM response from ${targetHost || "mock-api"}`;
}

function createMockApiServer() {
  const logs = [];
  let failures = [];
  let responseOverrides = [];
  let server = null;
  let boundPort = 0;

  function matchesRule(rule, ctx) {
    if (rule.host && ctx.targetHost !== rule.host) return false;
    if (rule.path && ctx.pathname !== rule.path) return false;
    if (rule.pathIncludes && !ctx.pathname.includes(rule.pathIncludes)) return false;
    if (rule.method && ctx.method !== rule.method.toUpperCase()) return false;
    if (rule.apiKey && ctx.apiKey !== rule.apiKey) return false;
    return true;
  }

  function sendJson(res, status, obj, extraHeaders = {}) {
    const payload = JSON.stringify(obj);
    res.writeHead(status, {
      "Content-Type": "application/json",
      "Content-Length": Buffer.byteLength(payload),
      ...extraHeaders
    });
    res.end(payload);
  }

  const requestHandler = (req, res) => {
    const chunks = [];
    req.on("data", (c) => chunks.push(c));
    req.on("end", () => {
      const rawBody = Buffer.concat(chunks);
      const bodyText = rawBody.toString("utf8");
      const urlObj = new URL(req.url, "http://127.0.0.1");
      const targetHost = req.headers["x-mock-target-host"] || "";
      const apiKey = extractApiKey(req, urlObj);

      const logEntry = {
        timestamp: new Date().toISOString(),
        method: req.method,
        pathname: urlObj.pathname,
        search: urlObj.search,
        query: Object.fromEntries(urlObj.searchParams.entries()),
        targetHost,
        apiKey,
        headers: { ...req.headers },
        bodyText: bodyText.length > 4096 ? bodyText.slice(0, 4096) + "...[truncated]" : bodyText,
        bodyLength: rawBody.length
      };
      logs.push(logEntry);

      const ctx = {
        method: req.method,
        pathname: urlObj.pathname,
        search: urlObj.search,
        query: logEntry.query,
        targetHost,
        apiKey,
        headers: req.headers,
        bodyText,
        rawBody
      };

      // 1. Check failure injection rules
      for (let i = 0; i < failures.length; i++) {
        const rule = failures[i];
        if (matchesRule(rule, ctx)) {
          if (typeof rule.times === "number") {
            rule.times -= 1;
            if (rule.times <= 0) failures.splice(i, 1);
          } else if (rule.once) {
            failures.splice(i, 1);
          }

          const status = rule.status || 500;
          if (typeof rule.body === "string") {
            res.writeHead(status, {
              "Content-Type": rule.contentType || "application/json",
              ...(rule.headers || {})
            });
            res.end(rule.body);
          } else {
            sendJson(res, status, rule.body || { error: { message: `Injected mock error ${status}` } }, rule.headers);
          }
          return;
        }
      }

      // 2. Check custom response overrides
      for (let i = 0; i < responseOverrides.length; i++) {
        const ov = responseOverrides[i];
        if (matchesRule(ov.matcher, ctx)) {
          if (ov.once) responseOverrides.splice(i, 1);
          const result = typeof ov.handler === "function" ? ov.handler(ctx) : ov.handler;
          if (typeof result === "string") {
            res.writeHead(200, { "Content-Type": "application/json" });
            res.end(result);
          } else {
            sendJson(res, result.status || 200, result.body !== undefined ? result.body : result, result.headers);
          }
          return;
        }
      }

      // 3. Default endpoint handlers
      const p = urlObj.pathname;

      // OpenAI / Groq / OpenRouter Chat Completions
      if (p.endsWith("/chat/completions")) {
        const content = buildDefaultChatContent(bodyText, targetHost);
        return sendJson(res, 200, {
          id: "chatcmpl-mock-123",
          object: "chat.completion",
          choices: [{ index: 0, message: { role: "assistant", content }, finish_reason: "stop" }],
          usage: { prompt_tokens: 10, completion_tokens: 20, total_tokens: 30 }
        });
      }

      // Groq / OpenAI Audio Transcriptions
      if (p.endsWith("/audio/transcriptions")) {
        return sendJson(res, 200, {
          task: "transcribe",
          language: "en",
          duration: 3.0,
          text: "Hello world test clip",
          words: [
            { word: "Hello", start: 0.1, end: 0.5 },
            { word: "world", start: 0.6, end: 1.0 },
            { word: "test", start: 1.2, end: 1.8 },
            { word: "clip", start: 1.9, end: 2.5 }
          ],
          segments: [{ id: 0, start: 0.1, end: 2.5, text: "Hello world test clip" }]
        });
      }

      // Gemini generateContent
      if (p.includes("/v1beta/models/") && p.endsWith(":generateContent")) {
        const content = buildDefaultChatContent(bodyText, targetHost);
        return sendJson(res, 200, {
          candidates: [
            {
              content: { parts: [{ text: content }], role: "model" },
              finishReason: "STOP"
            }
          ]
        });
      }

      // Giphy search
      if (p === "/v1/gifs/search") {
        return sendJson(res, 200, {
          data: [
            {
              id: "mock_gif_1",
              title: "Mock GIF",
              images: {
                original: {
                  url: "https://media.giphy.com/media/mock/giphy.gif",
                  mp4: "https://media.giphy.com/media/mock/giphy.mp4",
                  width: "480",
                  height: "270"
                },
                fixed_height: {
                  url: "https://media.giphy.com/media/mock/200.gif",
                  width: "356",
                  height: "200"
                }
              }
            }
          ],
          pagination: { total_count: 1, count: 1, offset: 0 },
          meta: { status: 200, msg: "OK" }
        });
      }

      // Google OAuth token
      if (p === "/token" || (targetHost === "oauth2.googleapis.com" && p.includes("token"))) {
        return sendJson(res, 200, {
          access_token: "mock_google_access_token",
          refresh_token: "mock_google_refresh_token",
          expires_in: 3600,
          token_type: "Bearer",
          scope: "https://www.googleapis.com/auth/youtube.upload https://www.googleapis.com/auth/youtube.readonly"
        });
      }

      // Google OAuth auth page
      if (p === "/o/oauth2/v2/auth") {
        res.writeHead(200, { "Content-Type": "text/html" });
        res.end("<html><body>Mock Google OAuth</body></html>");
        return;
      }

      // YouTube channels
      if (p === "/youtube/v3/channels") {
        return sendJson(res, 200, {
          kind: "youtube#channelListResponse",
          items: [
            {
              id: "UC_MOCK_CHANNEL_123",
              snippet: {
                title: "Mock YouTube Channel",
                customUrl: "@mockchannel"
              }
            }
          ]
        });
      }

      // YouTube Shorts upload
      if (p === "/upload/youtube/v3/videos") {
        return sendJson(res, 200, {
          kind: "youtube#video",
          id: "mock_yt_video_123",
          snippet: { title: "Mock Uploaded Short" },
          status: { privacyStatus: "public" }
        });
      }

      // TikTok OAuth & Publish
      if (p === "/v2/oauth/token/" || p === "/v2/oauth/token") {
        return sendJson(res, 200, {
          access_token: "mock_tiktok_access_token",
          refresh_token: "mock_tiktok_refresh_token",
          open_id: "mock_tiktok_open_id_123456",
          expires_in: 86400,
          scope: "user.info.basic,video.upload,video.publish"
        });
      }
      if (targetHost === "open.tiktokapis.com" || p.startsWith("/v2/")) {
        return sendJson(res, 200, {
          data: { publish_id: "mock_tiktok_pub_123" },
          error: { code: "ok", message: "" }
        });
      }

      // Instagram / Meta Graph API
      if (p.includes("/oauth/access_token")) {
        return sendJson(res, 200, {
          access_token: "mock_ig_access_token",
          token_type: "bearer",
          expires_in: 5184000
        });
      }
      if (targetHost === "graph.facebook.com" || p.startsWith("/v21.0/")) {
        return sendJson(res, 200, { id: "mock_ig_media_123", success: true });
      }

      // Fallback 404
      sendJson(res, 404, { error: "Mock endpoint not found", pathname: p, targetHost });
    });
  };

  return {
    get port() {
      return boundPort;
    },
    get url() {
      return boundPort ? `http://127.0.0.1:${boundPort}` : "";
    },
    start() {
      return new Promise((resolve, reject) => {
        server = http.createServer(requestHandler);
        server.on("error", reject);
        server.listen(0, "127.0.0.1", () => {
          boundPort = server.address().port;
          resolve({ port: boundPort, url: `http://127.0.0.1:${boundPort}` });
        });
      });
    },
    stop() {
      return new Promise((resolve) => {
        if (!server) return resolve();
        server.closeAllConnections?.();
        server.close(() => {
          server = null;
          boundPort = 0;
          resolve();
        });
      });
    },
    getLogs(filterFn) {
      return filterFn ? logs.filter(filterFn) : [...logs];
    },
    clearLogs() {
      logs.length = 0;
    },
    addFailure(rule) {
      failures.push({ ...rule });
    },
    clearFailures() {
      failures = [];
    },
    addResponseOverride(matcher, handler, once = false) {
      responseOverrides.push({ matcher, handler, once });
    },
    clearResponseOverrides() {
      responseOverrides = [];
    },
    reset() {
      logs.length = 0;
      failures = [];
      responseOverrides = [];
    }
  };
}

module.exports = { createMockApiServer };
